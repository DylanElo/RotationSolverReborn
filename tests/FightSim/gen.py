"""Writes Generated.g.cs: what RotationSolver's source generator and game sheets give the rotations.

python -I gen.py   (from tests/FightSim; re-run when a rotation starts using a new action, trait or status)

Every action, trait and status the compiled rotation files name gets a property or enum member; the sim's
game models (Bard.cs, Machinist.cs) give the ones that matter real behaviour.
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
# Each job's generated class gets the actions and traits its own sources name; the enums get everyone's.
JOBS = {
    "BardRotation": [
        "RotationSolver.Basic/Rotations/Basic/BardRotation.cs",
        "RotationSolver/RebornRotations/Ranged/BRD_Reborn.cs",
        "RotationSolver/RebornRotations/Ranged/BRD_Plan.cs",
        "RotationSolver/RebornRotations/FRUPad.cs",
        "tests/FightSim/Bard.cs",
    ],
    "MachinistRotation": [
        "RotationSolver.Basic/Rotations/Basic/MachinistRotation.cs",
        "RotationSolver/RebornRotations/Ranged/MCH_Reborn.cs",
        "RotationSolver/RebornRotations/Ranged/MCH_SyncPlus.cs",
        "RotationSolver/RebornRotations/Ranged/MCH_Plan.cs",
        "tests/FightSim/Machinist.cs",
    ],
}
SHARED = ["tests/FightSim/Fakes.cs", "tests/FightSim/Game.cs"]
read = lambda files: "\n".join((ROOT / s).read_text(encoding="utf-8") for s in files)
shared = read(SHARED)


def names(text):
    modified = set(re.findall(r"static partial void Modify(\w+)\(", text))
    actions = sorted(a for a in modified | set(re.findall(r"\b(\w+Pv[EP])\b", text)) if not a.startswith(("Modify", "Is")))
    traits = sorted(set(re.findall(r"\b(\w+Trait)\b", text)) - {"IBaseTrait", "BaseTrait"})
    return modified, actions, traits


jobs = {cls: names(read(files)) for cls, files in JOBS.items()}
all_actions = sorted(set(a for _, acts, _ in jobs.values() for a in acts) | set(names(shared)[1]))
statuses = sorted(set(re.findall(r"StatusID\.(\w+)", shared + read(f for fs in JOBS.values() for f in fs))) - {"None"})

out = ["// <auto-generated> by gen.py from the rotation sources. Do not edit. </auto-generated>",
       "namespace RotationSolver.Basic.Data",
       "{",
       "\tpublic enum ActionID : uint { None, " + ", ".join(all_actions) + " }",
       "\tpublic enum StatusID : uint { None, " + ", ".join(statuses) + " }",
       "}",
       "namespace RotationSolver.Basic.Rotations.Basic",
       "{"]
for cls, (modified, actions, traits) in jobs.items():
    out += [f"\tpublic partial class {cls} : RotationSolver.Basic.Rotations.CustomRotation", "\t{"]
    for a in actions:
        hook = f"Modify{a}(ref s)" if a in modified else ""
        out.append(f"\t\tpublic static IBaseAction {a} {{ get; }} = BaseAction.Create(ActionID.{a}, (ref ActionSetting s) => {{ {hook}; }});")
        if a in modified:
            out.append(f"\t\tstatic partial void Modify{a}(ref ActionSetting setting);")
    for t in traits:
        out.append(f"\t\tpublic static IBaseTrait {t} {{ get; }} = new BaseTrait();")
    out.append("\t}")
out.append("}")
(pathlib.Path(__file__).parent / "Generated.g.cs").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(all_actions)} actions, {len(statuses)} statuses, " + ", ".join(f"{c} {len(a)}" for c, (_, a, _) in jobs.items()))
